#!/usr/bin/env bash
# Regenerate the CDNAI app icon for iOS and Android from ONE source image.
#
# Source of truth: android_app/assets/icon/app_icon_source.jpg (the approved
# dark cat-face tile, 1080x1080, with its own rounded corners on a near-black
# frame).
#
# Outputs
#   Android  android/app/src/main/res/mipmap-*/ic_launcher*.png
#            values/colors.xml ic_launcher_background (frame colour)
#   iOS      assets/icon/ios/AppIcon.appiconset/*.png  (CI copies this into the
#            generated Runner project; Contents.json comes from flutter create)
#   Store    assets/icon/store/ic_launcher-playstore-512.png
#
# Requires ImageMagick (`magick`).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_DIR="$(cd "$HERE/.." && pwd)"
RES="$APP_DIR/android/app/src/main/res"
ICON_DIR="$APP_DIR/assets/icon"
SRC="$ICON_DIR/app_icon_source.jpg"
FRAME="#0C1013"

if [ ! -f "$SRC" ]; then
  echo "icon source not found at $SRC" >&2
  exit 1
fi

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# Measured on the source: the tile spans about x 57..1022, y 59..1021 with a
# corner radius of ~200px. The 860px crop at 110,110 lies fully inside the
# tile, so the square has no dark frame showing at its corners. iOS (and the
# Play Store) apply their own corner mask on top of this full-bleed square.
magick "$SRC" -crop 860x860+110+110 +repage -resize 1024x1024 \
  -colorspace sRGB -alpha off -strip "$WORK/square_1024.png"

# Rounded-tile cutout for Android's adaptive foreground: the tile keeps its own
# corners and sits on a solid frame-coloured background layer, like the
# approved image does.
magick -size 1080x1080 xc:black -fill white \
  -draw "roundrectangle 57,59 1022,1021 200,200" "$WORK/mask.png"
magick "$SRC" "$WORK/mask.png" -alpha off -compose CopyOpacity -composite \
  -strip "$WORK/tile_cutout_1080.png"

# ---- iOS app icon set ----------------------------------------------------
IOS_SET="$ICON_DIR/ios/AppIcon.appiconset"
mkdir -p "$IOS_SET" "$ICON_DIR/store"
# Filename -> pixel size, matching flutter create's AppIcon.appiconset.
IOS_SIZES=(
  "Icon-App-20x20@1x.png 20" "Icon-App-20x20@2x.png 40" "Icon-App-20x20@3x.png 60"
  "Icon-App-29x29@1x.png 29" "Icon-App-29x29@2x.png 58" "Icon-App-29x29@3x.png 87"
  "Icon-App-40x40@1x.png 40" "Icon-App-40x40@2x.png 80" "Icon-App-40x40@3x.png 120"
  "Icon-App-60x60@2x.png 120" "Icon-App-60x60@3x.png 180"
  "Icon-App-76x76@1x.png 76" "Icon-App-76x76@2x.png 152"
  "Icon-App-83.5x83.5@2x.png 167" "Icon-App-1024x1024@1x.png 1024"
)
for entry in "${IOS_SIZES[@]}"; do
  name="${entry% *}"
  size="${entry#* }"
  magick "$WORK/square_1024.png" -resize "${size}x${size}" -alpha off -strip \
    "$IOS_SET/$name"
done

# ---- Android legacy + store ----------------------------------------------
declare -A DPI=( [mdpi]=48 [hdpi]=72 [xhdpi]=96 [xxhdpi]=144 [xxxhdpi]=192 )
for dpi in "${!DPI[@]}"; do
  size="${DPI[$dpi]}"
  mkdir -p "$RES/mipmap-$dpi"
  magick "$WORK/square_1024.png" -resize "${size}x${size}" -strip \
    "$RES/mipmap-$dpi/ic_launcher.png"
  # Circle mask for launchers that ask for round icons.
  magick -size "${size}x${size}" xc:black -fill white \
    -draw "circle $((size / 2)),$((size / 2)) $((size / 2)),0" "$WORK/circle_$size.png"
  magick "$WORK/square_1024.png" -resize "${size}x${size}" "$WORK/circle_$size.png" \
    -alpha off -compose CopyOpacity -composite -strip \
    "$RES/mipmap-$dpi/ic_launcher_round.png"
  # Adaptive foreground: 108dp layer. The tile fills ~72% of the layer, which
  # keeps the artwork inside the 66% safe zone (rounded corners included).
  layer=$((size * 108 / 48))
  tile=$((layer * 72 / 100))
  magick -size "${layer}x${layer}" xc:none \
    \( "$WORK/tile_cutout_1080.png" -resize "${tile}x${tile}" \) \
    -gravity center -composite -strip "$RES/mipmap-$dpi/ic_launcher_foreground.png"
done

magick "$WORK/square_1024.png" -resize 512x512 -alpha off -strip \
  "$ICON_DIR/store/ic_launcher-playstore-512.png"

# Adaptive background colour: the frame colour the tile sits on.
COLORS="$RES/values/colors.xml"
sed -i "s|<color name=\"ic_launcher_background\">[^<]*</color>|<color name=\"ic_launcher_background\">$FRAME</color>|" "$COLORS"

# Adaptive icon XML: colour background + foreground. No monochrome layer: the
# artwork is a full colour illustration, so a themed silhouette would be wrong.
for xml in ic_launcher ic_launcher_round; do
  cat > "$RES/mipmap-anydpi-v26/$xml.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Adaptive launcher icon (Android 8.0+). Solid frame colour behind the
     rounded CDNAI tile, generated by tool/generate_app_icons.sh. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
XML
done

echo "app icons regenerated (iOS set, Android mipmaps, Play Store 512)"
